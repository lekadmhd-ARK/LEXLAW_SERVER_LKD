                </p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">1. Data yang Kami Kumpulkan</p>
                <p style="margin-bottom:6px">Data yang dikumpulkan dikelompokkan sebagai berikut:</p>
                <p style="margin-bottom:6px;margin-left:20px">• <b>Data identitas & akun:</b> nama, alamat email, kata sandi (terenkripsi), nama perusahaan, dan peran pengguna.</p>
                <p style="margin-bottom:6px;margin-left:20px">• <b>Data bisnis tenant:</b> regulasi, dokumen kontrak, catatan kerja, dan data hukum yang Anda unggah atau buat dalam akun perusahaan Anda.</p>
                <p style="margin-bottom:6px;margin-left:20px">• <b>Data teknis & keamanan:</b> alamat IP, lokasi kota berdasarkan IP (geolokasi level kota), alamat MAC perangkat (jika tersedia), sidik jari perangkat (device fingerprint — kombinasi unik browser &amp; perangkat), jenis perangkat/browser, alamat IP lokal, serta log aktivitas penggunaan untuk keperluan keamanan dan audit.</p>
                <p style="margin-bottom:6px;margin-left:20px">• <b>Data pembayaran:</b> Kami TIDAK menyimpan data kartu atau rekening Anda. Pembayaran diproses oleh penyedia payment gateway pihak ketiga (mis. Midtrans/QRIS) sesuai kebijakan mereka.</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">2. Dasar Hukum & Tujuan Pengolahan</p>
                <p style="margin-bottom:6px">Kami memproses data pribadi Anda dengan dasar hukum berupa persetujuan (consent) Anda pada saat pendaftaran, pelaksanaan perjanjian penggunaan SaaS, dan pemenuhan kewajiban hukum, untuk tujuan:</p>
                <p style="margin-bottom:6px;margin-left:20px">• Menyediakan, mengoperasikan, dan menjaga keamanan layanan LexLaw.</p>
                <p style="margin-bottom:6px;margin-left:20px">• Personalisasi fitur, staf, dan kuota akun sesuai paket langganan Anda.</p>
                <p style="margin-bottom:6px;margin-left:20px">• Mengirim notifikasi penting (email verifikasi, reset password, invoice, perpanjangan).</p>
                <p style="margin-bottom:6px;margin-left:20px">• Analisis agregat dan anonim untuk perbaikan layanan (tanpa mengidentifikasi individu).</p>
                <p style="margin-bottom:6px;margin-left:20px">• Memenuhi kewajiban audit hukum dan akuntansi.</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">3. Isolasi Data Antar Pelanggan (Multi-Tenant)</p>
                <p style="margin-bottom:6px">LexLaw adalah platform SaaS multi-tenant. Setiap perusahaan pelanggan terisolasi secara logis: seluruh data hukum (regulasi, dokumen, catatan, workspace) yang dimiliki satu perusahaan TIDAK dapat diakses oleh perusahaan lain maupun oleh pengguna luar tanpa otorisasi. Super admin LexLaw hanya dapat mengakses data tersebut untuk dukungan teknis atau kewajiban hukum, dan seluruh akses tercatat dalam log audit.</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">4. Penyimpanan & Transfer Data</p>
                <p style="margin-bottom:6px">Data Anda disimpan dalam server yang berlokasi di wilayah Indonesia dan dilindungi dengan kontrol akses, enkripsi kata sandi (bcrypt), serta koneksi HTTPS (TLS). Data tidak dijual kepada pihak ketiga mana pun. Kami tidak mentransfer data pribadi ke luar yurisdiksi Indonesia tanpa dasar hukum yang sah.</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">5. Hak Anda Sebagai Pemilik Data Pribadi</p>
                <p style="margin-bottom:6px">Sesuai UU PDP, Anda berhak:</p>
                <p style="margin-bottom:6px;margin-left:20px">• Mengakses dan memperoleh salinan data pribadi Anda.</p>
                <p style="margin-bottom:6px;margin-left:20px">• Memperbaiki atau memperbarui data yang tidak akurat.</p>
                <p style="margin-bottom:6px;margin-left:20px">• Menarik kembali persetujuan pemrosesan data.</p>
                <p style="margin-bottom:6px;margin-left:20px">• Meminta penghapusan data (hak untuk dilupakan) sesuai ketentuan peraturan.</p>
                <p style="margin-bottom:6px;margin-left:20px">• Mengajukan pengaduan kepada lembaga pengawas pelindungan data pribadi.</p>
                <p style="margin-bottom:6px">Untuk menggunakan hak tersebut, kirim permintaan melalui <b>support@lexlaw.arktech.id</b>. Kami akan menanggapi paling lambat 30 hari kalender.</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">6. Retensi Data</p>
                <p style="margin-bottom:6px">Data akun dan data hukum tenant disimpan selama langganan aktif. Setelah akun dihentikan/periode percobaan berakhir tanpa langganan, data dapat dihapus atau dianonimkan sesuai kebijakan retensi maksimal 12 bulan, kecuali wajib disimpan lebih lama karena kewajiban hukum (mis. catatan pembayaran dan audit internal maksimal 10 tahun).</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">7. Keamanan Data</p>
                <p style="margin-bottom:6px">Kami menerapkan langkah keamanan yang wajar: enkripsi kata sandi, HTTPS, otentikasi pengguna, pembatasan akses berbasis peran (owner/admin/editor/viewer), rate-limiting login, sesi aman, dan pencatatan audit log. Jika terjadi pelanggaran data pribadi yang berisiko tinggi, kami akan memberi tahu Anda dan otoritas terkait sesuai UU PDP.</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">8. Perubahan Kebijakan & Kontak</p>
                <p style="margin-bottom:6px">Kami dapat memperbarui Kebijakan Privasi ini sewaktu-waktu. Perubahan yang material akan diinformasikan melalui email atau demonstrasi di platform. Untuk pertanyaan dan pengaduan perlindungan data, hubungi kami di <b>support@lexlaw.arktech.id</b>.</p>

