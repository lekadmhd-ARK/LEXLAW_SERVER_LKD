            <div style="font-size:14px;color:var(--text);line-height:1.8">

                <p style="margin-bottom:16px;color:var(--text-muted)">
                    Dokumen ini merupakan <b>Addendum Pemrosesan Data (Data Processing Agreement)</b> yang melekat pada Syarat &amp; Ketentuan LexLaw, dibuat dalam rangka pemenuhan Undang-Undang Nomor 27 Tahun 2022 tentang Pelindungan Data Pribadi ("UU PDP"). Dengan mendaftar dan menggunakan layanan, Pengguna ("Kontroler" / Pemilik Data) dan LexLaw ("Prosesor") dianggap menyetujui perjanjian ini.
                </p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">1. Para Pihak & Peran</p>
                <p style="margin-bottom:6px">• <b>Kontroler:</b> Pengguna/perusahaan pelanggan yang menentukan tujuan dan cara pengolahan data pribadinya.</p>
                <p style="margin-bottom:6px">• <b>Prosesor:</b> LexLaw, yang mengolah data pribadi atas nama dan sesuai instruksi Kontroler untuk menyediakan layanan SaaS.</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">2. Ruang Lingkup Pengolahan</p>
                <p style="margin-bottom:6px">Prosesor mengolah data pribadi yang dimasukkan Kontroler ke dalam platform (nama, email, peran pengguna, dan data bisnis/hukum tenant) semata-mata untuk: (a) menyediakan dan mengoperasikan layanan; (b) keamanan, audit, dan pemulihan data; (c) mematuhi kewajiban hukum. Prosesor tidak akan menggunakan data untuk kepentingan lain atau menjual data kepada pihak ketiga.</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">3. Instruksi & Kepatuhan</p>
                <p style="margin-bottom:6px">Prosesor hanya akan mengolah data pribadi atas instruksi tertulis Kontroler, kecuali diwajibkan oleh peraturan perundang-undangan (dalam hal ini Prosesor akan memberi tahu Kontroler sepanjang diizinkan hukum). Prosesor akan membantu Kontroler memenuhi kewajiban berdasarkan UU PDP, termasuk menanggapi hak subjek data dan pemberitahuan pelanggaran data.</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">4. Sub-Prosesor</p>
                <p style="margin-bottom:6px">Prosesor dapat menggunakan sub-prosesor (mis. penyedia server/hosting, penyedia email transaksional, penyedia payment gateway) semata-mata untuk pelaksanaan layanan. Daftar sub-prosesor terkini tersedia atas permintaan melalui <b>support@lexlaw.arktech.id</b>. Prosesor menjamin setiap sub-prosesor terikat kewajiban perlindungan data yang setidaknya setara dengan DPA ini.</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">5. Keamanan Pemrosesan</p>
                <p style="margin-bottom:6px">Prosesor menerapkan langkah teknis dan organisasi yang memadai, termasuk enkripsi kata sandi, HTTPS/TLS, kontrol akses berbasis peran, isolasi data antar tenant, rate-limiting, dan audit log, untuk melindungi data dari akses tidak sah, perubahan, dan kebocoran.</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">6. Pelanggaran Data</p>
                <p style="margin-bottom:6px">Jika terjadi insiden keamanan yang mengakibatkan pelanggaran data pribadi, Prosesor akan memberitahu Kontroler tanpa penundaan yang tidak semestinya, memberikan detail yang wajar, dan membantu memitigasi dampaknya sesuai UU PDP.</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">7. Penghentian & Penghapusan Data</p>
                <p style="margin-bottom:6px">Pada penghentian layanan, atas pilihan Kontroler dan dalam jangka waktu yang wajar, Prosesor akan memulangkan atau menghapus seluruh data pribadi yang diolahnya, kecuali wajib disimpan berdasarkan hukum. Prosesor akan membantu Kontroler mengekspor data (data portability) selama langganan aktif.</p>

                <hr style="border:none;border-top:1px solid var(--line);margin:24px 0">

                <p style="font-weight:700;font-size:15px;color:var(--accent);margin:24px 0 8px">8. Hukum yang Berlaku & Kontak</p>
                <p style="margin-bottom:6px">DPA ini diatur oleh hukum Republik Indonesia. Perbedaan interpretasi yang timbul akan diselesaikan secara musyawarah terlebih dahulu. Pertanyaan dan permintaan terkait DPA dapat diajukan ke <b>support@lexlaw.arktech.id</b>.</p>

